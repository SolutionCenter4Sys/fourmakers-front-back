-- Tabela de ocorrências CNAB
-- Armazena os códigos de ocorrência possíveis e suas descrições

CREATE TABLE IF NOT EXISTS tb_cnab_ocorrencia (
    id CHAR(36) PRIMARY KEY,
    modelo_cnab VARCHAR(50) NOT NULL COMMENT 'Modelo do CNAB (ex: CNAB240_ITAU_V085)',
    codigo VARCHAR(2) NOT NULL COMMENT 'Código da ocorrência (ex: 00, BD, AE)',
    descricao VARCHAR(255) NOT NULL COMMENT 'Descrição da ocorrência',
    tipo VARCHAR(20) NOT NULL COMMENT 'Tipo: SUCESSO, ERRO, AVISO, AGENDADO',
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_cnab_ocorrencia (modelo_cnab, codigo)
);

